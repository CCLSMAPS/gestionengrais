create or replace function public.verify_bon_public(p_bon_no text)
returns table (
  bon_no text,
  sortie_date date,
  camp text,
  designation text,
  qty numeric
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    b.bon_no,
    b.sortie_date,
    b.camp,
    b.designation,
    b.qty
  from public.bon_sorties b
  where lower(trim(b.bon_no)) = lower(trim(coalesce(p_bon_no, '')))
  order by b.id asc;
$$;

revoke all on function public.verify_bon_public(text) from public;
grant execute on function public.verify_bon_public(text) to anon, authenticated;

