-- ============================================================
-- 1) منع تجاوز الكمية المتبقية في الفاتورة على مستوى قاعدة البيانات
-- ============================================================
create or replace function public.enforce_withdrawal_remaining()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_invoice_qty numeric;
  v_other_taken numeric;
begin
  if new.qty is null or new.qty <= 0 then
    raise exception 'كمية الاستلام يجب أن تكون أكبر من الصفر';
  end if;

  select i.qty into v_invoice_qty
  from public.invoices i
  where i.id = new.invoice_id
  for update;

  if v_invoice_qty is null then
    raise exception 'الفاتورة المرتبطة غير موجودة';
  end if;

  select coalesce(sum(w.qty), 0) into v_other_taken
  from public.withdrawals w
  where w.invoice_id = new.invoice_id
    and (tg_op = 'INSERT' or w.id <> new.id);

  if (v_other_taken + new.qty) > v_invoice_qty then
    raise exception 'الكمية المطلوبة (%) تتجاوز المتبقي في الفاتورة (المتاح: %)',
      new.qty, greatest(v_invoice_qty - v_other_taken, 0);
  end if;

  return new;
end;
$$;

drop trigger if exists trg_enforce_withdrawal_remaining on public.withdrawals;
create trigger trg_enforce_withdrawal_remaining
  before insert or update of qty, invoice_id
  on public.withdrawals
  for each row
  execute function public.enforce_withdrawal_remaining();

